"""Render the verified numerical study into the LaTeX manuscript source."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import shutil


def number(value, digits=6):
    formatted = f"{value:.{digits}g}"
    if 'e' in formatted:
        mantissa, exponent = formatted.split('e')
        return rf"${mantissa}\times10^{{{int(exponent)}}}$"
    return formatted


def table(headers, rows, caption, label):
    cells = [" & ".join(str(value) for value in row) + r" \\" for row in rows]
    wide = len(headers) > 4
    return (r"\begin{table}[htbp]\centering\small" + "\n"
            + r"\caption{" + caption + r"}\label{" + label + "}\n"
            + (r"\resizebox{\linewidth}{!}{" if wide else "")
            + r"\begin{tabular}{" + "r"*len(headers) + r"}\toprule" + "\n"
            + " & ".join(headers) + r" \\\midrule" + "\n" + "\n".join(cells)
            + "\n" + r"\bottomrule\end{tabular}" + ("}" if wide else "") + r"\end{table}" + "\n")


def figure(name, caption, label):
    return (r"\begin{figure}[htbp]\centering\includegraphics[width=\linewidth]{figures/" + name + ".pdf}\n"
            + r"\caption{" + caption + r"}\label{" + label + r"}\end{figure}" + "\n")


